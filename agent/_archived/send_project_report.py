def send_tg(chat_id):
    if not TELEGRAM_TOKEN:
        print("NO TOKEN FOUND")
        return
    url = f"https://api.telegram.org/bot{TELEGRAM_TOKEN.strip()}/sendMessage"
    proxies = {}
    if PROXY_URL:
        proxy = PROXY_URL.replace("socks5://", "socks5h://")
        proxies = {"https": proxy, "http": proxy}
    try:
        resp = requests.post(url, json={"chat_id": chat_id, "text": report_text, "parse_mode": "HTML"}, proxies=proxies, timeout=15)
        print(f"Sent to {chat_id}: {resp.status_code} {resp.text[:100]}")
    except Exception as e:
        print(f"Error {chat_id}: {e}")

