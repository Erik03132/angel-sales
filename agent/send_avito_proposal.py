def send_msg(text, dialog_id=ANDREY_ID):
    resp = requests.post(f"{SANDBOX_URL}/im.message.add.json", json={
        "DIALOG_ID": dialog_id,
        "MESSAGE": text[:4000]
    }, timeout=15)
    if resp.status_code == 200 and resp.json().get("result"):
        msg_id = resp.json()["result"]
        print(f"  ✅ Отправлено (msg #{msg_id})")
        return msg_id
