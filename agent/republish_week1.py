# ══════════════════════════════════════
# ПУБЛИКАЦИЯ
# ══════════════════════════════════════

session = vk_api.VkApi(token=GROUP_TOKEN)
vk = session.get_api()

from datetime import datetime, timedelta

now = datetime.now()
start = now.replace(hour=10, minute=0, second=0, microsecond=0)
if start <= now:
    start += timedelta(days=1)

print(f"📅 Планирую 7 постов с {start.strftime('%d.%m.%Y %H:%M')}")

results = []
for i, text in enumerate(POSTS):
    idx = i + 1
    publish_date = start + timedelta(days=i)
    attachment = PHOTOS.get(idx, '')

    result = vk.wall.post(
        owner_id=f'-{VK_GID}',
        from_group=1,
        message=text,
        attachments=attachment,
        publish_date=int(publish_date.timestamp()),
    )
    post_id = result['post_id']
    results.append(post_id)
    print(f"  ✅ #{idx} → post_id={post_id} на {publish_date.strftime('%d.%m %H:%M')} | фото: {attachment}")
    time.sleep(1)

print(f"\n🎉 Опубликовано {len(results)} постов!")

# Обновляем posted_log
log_path = os.path.join(os.path.dirname(__file__), '..', 'vk_content', 'podvorye', 'posted_log.json')
log = {}
for i, post_id in enumerate(results):
    idx = i + 1
    publish_date = start + timedelta(days=i)
    log[str(idx)] = {
        'post_id': post_id,
        'published_at': publish_date.isoformat(),
        'scheduled': True,
        'title': f'Пост {idx} (переписан, Imagen 4)',
    }
with open(log_path, 'w') as f:
    json.dump(log, f, ensure_ascii=False, indent=2)
print("💾 posted_log.json обновлён")
